public class Vehicle {
  private  String engine;
  private  int wheels;
  private int seats;
  private  int  fuelTank;
  private String lights;


public Vehicle(){
    engine="gass";
    wheels=4;
    seats=4;
    fuelTank=14;
    lights="YES";
}

public String getEngine(){
    return engine;
}
public int getWheels(){
    return wheels;
}
public int seats(){
    return seats;
}
public int getFuelTank(){
    return fuelTank;
}
public String getLights(){
    return lights;
}







}